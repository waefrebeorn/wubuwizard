#define DEFINE_ROW_DOT(TY, NT)                                                                  \
IQ_AVX2 static void row_dot_##TY##_##NT(const uint8_t *row, int nblocks,                          \
                                       const block_q8_K *const *y, float *res)                   \
{                                                                                                \
    __m256 accf[NT];                                                                             \
    for (int t = 0; t < NT; ++t) accf[t] = _mm256_setzero_ps();                                   \
    for (int i = 0; i < nblocks; ++i) {                                                           \
        const uint8_t *blk = row + (size_t) i * FMT_BYTES_##TY;                                   \
        __m256i acci[NT];                                                                         \
        for (int t = 0; t < NT; ++t) acci[t] = _mm256_setzero_si256();                             \
        for (int j = 0; j < 4; ++j) {                                                             \
            for (int half = 0; half < 2; ++half) {                                                \
                __m256i g, sgn, sc;                                                               \
                fmt_decode_##TY(blk, j, half, &g, &sgn, &sc);                                     \
                const int off = 64 * j + 32 * half;                                               \
                for (int t = 0; t < NT; ++t) {                                                    \
                    const __m256i yv = _mm256_loadu_si256((const __m256i *) (y[t][i].qs + off));   \
                    const __m256i ys = _mm256_sign_epi8(yv, sgn);                                 \
                    acci[t] = _mm256_add_epi32(acci[t], _mm256_madd_epi16(_mm256_maddubs_epi16(g, ys), sc)); \
                }                                                                                 \
            }                                                                                     \
        }                                                                                         \
        const float dx = h2f(u16(blk));                                                           \
        for (int t = 0; t < NT; ++t)                                                              \
            accf[t] = _mm256_fmadd_ps(_mm256_set1_ps(dx * y[t][i].d), _mm256_cvtepi32_ps(acci[t]), accf[t]); \
    }                                                                                             \
    for (int t = 0; t < NT; ++t) res[t] = FMT_K_##TY * hsum_ggml(accf[t]);                         \
}

