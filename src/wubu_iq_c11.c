/*
 * wubu_iq_c11.c -- the i-quant expert rows in 256-bit lanes, several tokens at once.
 * C11 translation of maya's src/kernels/cpu/iq_avx2.cpp (1:1: same constants, same
 * order of floating-point operations, same integer lanes). The project is C11 only,
 * so the C++ template specialisations become plain functions + static const tables
 * holding the same constants, and std::atomic<bool> becomes C11 <stdatomic.h>.
 *
 * Why this shape: each 32-value chunk is decoded once - grid lookups, one sign
 * vector, one scale vector - and every token of the verify window applies them with
 * a load, a `sign`, a `maddubs`, a `madd` and an `add`. ggml-cpu's own AVX2 dot
 * products for these formats are single-token: every token re-does the codebook
 * lookups and the sign expansion. The sign vector is ggml's bit_selector pattern
 * (ggml-cpu/arch/x86/quants.c): pshufb-broadcast of each sign byte, AND with the
 * bit selector, CMPEQ, OR with one, `vpsignb`. The result is BIT-IDENTICAL to
 * ggml's AVX2 dot: the same exact integer lanes per block and ggml's float steps in
 * ggml's order (one fmadd per block with d_x * d_y, hsum_float_8, then the format's
 * constant).
 *
 * Formats: IQ2_XXS (16), IQ2_XS (17), IQ3_XXS (18), IQ3_S (21), IQ2_S (22),
 * IQ4_XS (23), Q4_K (12), Q5_K (13). IQ1_M (29) shares its grid, scale and delta
 * decode across tokens, preserving ggml's two float accumulators.
 *
 * Block layouts and codebooks are ggml's own (ggml-common.h, -DGGML_COMMON_DECL_C
 * / -DGGML_COMMON_IMPL_C). Every vector function carries
 * __attribute__((target("avx2,fma,f16c"))) so this file builds without a global
 * -mavx2; the public entry points are plain C and test __builtin_cpu_supports
 * before calling in.
 *
 * Environment knobs are maya's names, kept so the tuning behaviour is unchanged:
 *   MAYA_IQ_PF_ROWS   prefetch distance for the IQ2_XXS rows1 path (default 2, 0 off)
 *   MAYA_IQ2_VAR      IQ2_XXS rows1 decode variant 0/1/2 (default 1)
 *   MAYA_IQ2XXS_1T    opt in to the IQ2_XXS rows1 path (default off)
 *   DS4_IQ1M_PDEP     0/1 forces the scalar IQ1_M grid decode on a BMI2 CPU
 */
