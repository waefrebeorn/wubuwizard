/* AVX2 + FMA + F16C: exactly the target attribute's instruction set (a CPU that
 * has AVX2 has both in practice; the checks just make the guard exact). */
static int iq_cpu_ok(void)
{
    static _Atomic int cached = -2;
    int v = atomic_load_explicit(&cached, memory_order_relaxed);
    if (v == -2) {
        v = (__builtin_cpu_supports("avx2") && __builtin_cpu_supports("fma") &&
             __builtin_cpu_supports("f16c")) ? 1 : 0;
        atomic_store_explicit(&cached, v, memory_order_relaxed);
    }
    return v;
}

static int iq_type_ok(int t)
{
    return t == 16 || t == 17 || t == 18 || t == 21 || t == 22 || t == 23 || t == 29 || t == 12 || t == 13 ||
           t == 19 || t == 14 || t == 40 || t == 42 || t == 8;
}

