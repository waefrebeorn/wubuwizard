/* ggml's unpack of a K-quant block's 12 scale bytes: utmp[0..1] = the 8 6-bit
 * scales, utmp[2..3] = the 8 mins */
static inline void k_scales(const uint8_t *s12, uint32_t utmp[4])
{
    const uint32_t kmask1 = 0x3f3f3f3f, kmask2 = 0x0f0f0f0f, kmask3 = 0x03030303;
    memcpy(utmp, s12, 12);
    utmp[3] = ((utmp[2] >> 4) & kmask2) | (((utmp[1] >> 6) & kmask3) << 4);
    const uint32_t uaux = utmp[1] & kmask1;
    utmp[1] = (utmp[2] & kmask2) | (((utmp[0] >> 6) & kmask3) << 4);
    utmp[2] = uaux;
    utmp[0] &= kmask1;
}

